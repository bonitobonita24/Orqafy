// review-scope.mjs — deterministic code-review pre-scope tool (V32.51).
// Zero runtime deps (node:* stdlib only). Task 1: diff parser + conservative
// review-worthiness gate. Later tasks add the CLI entry behind the
// import.meta.url === main guard.
//
// DESIGN LAW 2 (conservative gate): default = INCLUDE. Only exclude
// certain-noise (lockfiles, generated output, binary/asset files, .snap
// snapshots, generated-header markers). Always KEEP .d.ts, deletions,
// tests, config, docs, migrations.

/**
 * Parse a unified diff (as produced by `git diff`) into per-file records.
 * @param {string} text
 * @returns {{path: string, status: string, added: string[]}[]}
 */
function parseDiff(text) {
  const lines = text.split("\n");
  const files = [];
  let current = null;

  const fileHeaderRe = /^diff --git a\/(.+?) b\/(.+)$/;

  for (const line of lines) {
    const headerMatch = line.match(fileHeaderRe);
    if (headerMatch) {
      current = { path: headerMatch[2], status: "modified", added: [] };
      files.push(current);
      continue;
    }
    if (!current) continue;

    if (line.startsWith("deleted file mode")) {
      current.status = "deleted";
      continue;
    }
    if (line.startsWith("rename from") || line.startsWith("rename to")) {
      current.status = "renamed";
      continue;
    }
    if (line.startsWith("new file mode")) {
      current.status = "added";
      continue;
    }
    if (line.startsWith("+++")) {
      // header line — never a content line, always skip
      continue;
    }
    if (line.startsWith("+")) {
      current.added.push(line.slice(1));
    }
  }

  return files;
}

const SKIP_PATTERNS = [
  /(^|\/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock)$/,
  /(^|\/)(dist|\.next|node_modules)\//,
  /\.(png|jpe?g|gif|svg|ico|webp|woff2?|map)$/i,
  /\.snap$/,
];

const GENERATED_HEADER_RE = /@generated|DO NOT EDIT|prisma-client|Code generated by/;

/**
 * Conservative review-worthiness gate. Default = INCLUDE; excludes only
 * certain-noise. Never excludes .d.ts, deletions, tests, config, docs,
 * migrations.
 * @param {string} path
 * @param {string[]} addedLines
 * @returns {{worthy: boolean, reason: string}}
 */
function reviewWorthy(path, addedLines) {
  for (const re of SKIP_PATTERNS) {
    if (re.test(path)) {
      return { worthy: false, reason: `matches skip pattern: ${re}` };
    }
  }

  const headSlice = (addedLines || []).slice(0, 5);
  if (headSlice.some((line) => GENERATED_HEADER_RE.test(line))) {
    return { worthy: false, reason: "generated-file header marker detected" };
  }

  return { worthy: true, reason: "no exclusion matched — default include" };
}

